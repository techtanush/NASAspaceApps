// Compile the frozen schema at build time; the browser never evaluates generated code strings.
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const require = createRequire(new URL('../../apps/web/package.json', import.meta.url));
const Ajv2020 = require('ajv/dist/2020').default;
const addFormats = require('ajv-formats').default;
const standaloneCode = require('ajv/dist/standalone').default;
const schema = JSON.parse(readFileSync(new URL('../../contracts/scientific-assurance.schema.json', import.meta.url), 'utf8'));
const ajv = new Ajv2020({ strict: false, code: { source: true, esm: true, lines: true } });
addFormats(ajv);
let code = '// Generated by scripts/ui/generate_assurance_validator.mjs from the frozen assurance schema.\n'
  + standaloneCode(ajv, ajv.compile(schema));
// AJV standalone helpers are tiny runtime imports. Do not ship the schema compiler or eval.
const imports = new Map();
code = code.replace(/require\("([^"\n]+)"\)/g, (_match, module) => {
  if (!['ajv/dist/runtime/ucs2length', 'ajv-formats/dist/formats'].includes(module)) throw new Error(`Unexpected runtime helper: ${module}`);
  if (!imports.has(module)) imports.set(module, `helper${imports.size}`);
  return imports.get(module);
});
for (const [module, name] of imports) {
  if (module === 'ajv/dist/runtime/ucs2length') code = code.replace(`${name}.default`, `(${name}.default ?? ${name})`);
}
code = [...imports].map(([module, name]) => `import * as ${name}Module from '${module}';\nconst ${name} = ${name}Module.default ?? ${name}Module;\n`).join('') + code;
const output = new URL('../../apps/web/src/generated/validateAssurance.js', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== code) throw new Error('Assurance validator is stale: regenerate it.');
} else writeFileSync(output, code);
console.log(`Assurance validator verified: ${fileURLToPath(output)}`);
