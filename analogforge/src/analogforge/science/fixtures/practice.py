"""Practice dataset generators (architecture 40 section 3): GeoTIFF + ``manifest.yaml`` per dataset.

``generate_all(out_dir, **kwargs)`` writes the five datasets of 40 section 3 (plus the Moon thermal product and the
Earth water mask) under ``out_dir/<dataset_id>/``.  Output is byte-deterministic for equal parameters: GeoTIFFs are
written uncompressed without timestamps, manifests are dumped with fixed key order.

SYNTHETIC PRACTICE DATA - never labelled NASA, NASADEM, MOLA or LOLA.
"""

