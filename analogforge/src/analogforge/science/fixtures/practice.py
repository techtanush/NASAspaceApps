@dataclass(frozen=True)
class RasterFile:
    """One raster file of a dataset before writing."""

    path: str
    array: NDArray[np.number]
    origin_x_m: float
    origin_y_m: float
    cell_size_m: float
    epsg: int | None
    wkt: str | None
    nodata: float | None
    role: str = "DATA"


@dataclass(frozen=True)
class PracticeProduct:
    """A generated dataset: the manifest (checksums unset) and its raster files."""

    dataset_id: str
    manifest: DatasetManifest
    rasters: tuple[RasterFile, ...]

    @property
    def primary(self) -> RasterFile:
        return next(r for r in self.rasters if r.path == self.manifest.primary_file)

    def raster(self, path: str) -> RasterFile:
        return next(r for r in self.rasters if r.path == path)


@dataclass(frozen=True)
class PracticeOptions:
    """All generator parameters in one place (``generate_all`` keyword arguments map onto these)."""

    seed: int = pe.SEED_DEFAULT
    earth: pe.EarthGridParams = field(default_factory=pe.EarthGridParams)
    mars_fractions: tuple[tuple[float, float], ...] = pt.MARS_FRACTIONS
    moon_fractions: tuple[tuple[float, float], ...] = pt.MOON_FRACTIONS


def make_options(seed: int = pe.SEED_DEFAULT, **kwargs: Any) -> PracticeOptions:
    """Build options from keyword arguments: ``mars_fractions``, ``moon_fractions`` (alias ``target_fractions`` for
    Mars) and any ``EarthGridParams`` field (``moat_cells``, ``ramp_slope_deg`` ...)."""
    earth_names = {f.name for f in fields(pe.EarthGridParams)}
    earth_kwargs: dict[str, Any] = {k: kwargs.pop(k) for k in list(kwargs) if k in earth_names and k != "seed"}
    mars = kwargs.pop("mars_fractions", kwargs.pop("target_fractions", pt.MARS_FRACTIONS))
    moon = kwargs.pop("moon_fractions", pt.MOON_FRACTIONS)
    if kwargs:
        raise TypeError(f"unknown generator parameters: {sorted(kwargs)}")
    earth = replace(pe.EarthGridParams(), seed=seed, **earth_kwargs)
    return PracticeOptions(
        seed=seed,
        earth=earth,
        mars_fractions=tuple((float(s), float(f)) for s, f in mars),
        moon_fractions=tuple((float(s), float(f)) for s, f in moon),
    )


def _base_manifest(dataset_id: str, title: str, **kwargs: Any) -> DatasetManifest:
    notes = [LABEL, f"generator {dataset_id} version {GENERATOR_VERSION}, seed {kwargs.pop('seed')}"]
    notes.extend(kwargs.pop("extra_notes", []))
    return DatasetManifest(
        dataset_id=dataset_id,
        title=title,
        provider=PROVIDER,
        is_synthetic=True,
        pixel_registration="CORNER",  # cells are areas anchored at the grid corner by construction
        license_note=LICENSE_NOTE,
        citation=f"AnalogForge synthetic practice generator {dataset_id} v{GENERATOR_VERSION}",
        product_identity=ProductIdentity(
            product_id=f"SYNTHETIC_{dataset_id.upper().replace('-', '_')}", version="1.0.0"
        ),
        acquisition=Acquisition(description="generated; no acquisition"),
        notes=notes,
        **kwargs,
    )


def earth_grid_product(opts: PracticeOptions) -> PracticeProduct:
    arrays = pe.build_earth_grid(opts.earth)
    elev = RasterFile(
        f"{DATASET_EARTH_GRID}.tif",
        pe.elevation_file_array(arrays),
        pe.SW_EASTING_M,
        pe.NORTH_NORTHING_M,
        pe.CELL_SIZE_M,
        pe.EPSG,
        None,
        pe.NODATA_VALUE,
    )
    water = RasterFile(
        f"{DATASET_EARTH_GRID}-water.tif",
        pe.water_file_array(arrays),
        pe.SW_EASTING_M,
        pe.NORTH_NORTHING_M,
        pe.CELL_SIZE_M,
        pe.EPSG,
        None,
        None,
        role="MASK",
    )
    manifest = _base_manifest(
        DATASET_EARTH_GRID,
        "SYNTHETIC practice Earth grid (192x192, 60 m)",
        seed=opts.seed,
        body="EARTH",
        role="EARTH_TERRAIN",
        format="GEOTIFF",
        files=[DatasetFile(path=elev.path, role="DATA"), DatasetFile(path=water.path, role="MASK")],
        primary_file=elev.path,
        quantity="ELEVATION",
        units="m",
        nodata_value=pe.NODATA_VALUE,
        vertical_reference="SYNTHETIC_REFERENCE_ONLY",
        crs=CrsSpec(epsg=pe.EPSG),
        longitude_convention="PROJECTED",
        latitude_type="GEODETIC",
        declared_native_resolution_m=pe.CELL_SIZE_M,
        extra_notes=["water mask file: uint8, 1 = water"],
    )
    return PracticeProduct(DATASET_EARTH_GRID, manifest, (elev, water))


