def generate(out_dir: str | Path, *, seed: int = SEED_DEFAULT, only: Sequence[str] | None = None) -> list[str]:
    """Write the nine datasets of architecture 39 section 5 below ``out_dir/<dataset_id>/``; return the ids written."""
    chosen = list(ALL_IDS if only is None else only)
    unknown = [d for d in chosen if d not in _BUILDERS]
    if unknown:
        raise KeyError(f"unknown mock drop datasets: {unknown}")
    root = Path(out_dir)
    for dataset_id in chosen:
        manifest = _BUILDERS[dataset_id](root, seed)
        (root / dataset_id / "manifest.yaml").write_text(manifest_yaml(manifest), encoding="utf-8")
    return chosen
