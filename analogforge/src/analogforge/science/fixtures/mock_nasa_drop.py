def _manifest(dataset_id: str, title: str, seed: int, **kwargs: Any) -> DatasetManifest:
    notes = [LABEL, f"mock drop generator version 1.0.0, seed {seed}", *kwargs.pop("extra_notes", [])]
    return DatasetManifest(
        dataset_id=dataset_id,
        title=title,
        provider=PROVIDER,
        is_synthetic=True,
        license_note=LICENSE_NOTE,
        citation=f"AnalogForge synthetic mock NASA drop {dataset_id} v1.0.0",
        product_identity=ProductIdentity(
            product_id=f"SYNTHETIC_{dataset_id.upper().replace('-', '_')}", version="1.0.0"
        ),
        acquisition=Acquisition(description="generated; no acquisition"),
        notes=notes,
        **kwargs,
    )


def _geographic_wkt(body: str) -> str:
    return str(body_geometry(body).geographic_crs().to_wkt())  # type: ignore[arg-type]


def _smooth(rows: int, cols: int, amplitude: float, base: float, seed: int, tag: str) -> NDArray[np.float64]:
    rng = dataset_rng(seed, tag)
    p = rng.uniform(0, 2 * math.pi, size=2)
    r, c = np.meshgrid(np.arange(rows, dtype=np.float64), np.arange(cols, dtype=np.float64), indexing="ij")
    return np.asarray(
        base + amplitude * np.sin(r / (rows / 5.0) + p[0]) * np.cos(c / (cols / 4.0) + p[1]), dtype=np.float64
    )


