"""Live review schemas expose only authoritative opaque claim identifiers."""

import json
from copy import deepcopy
from uuid import uuid4

import jsonschema
import pytest

from analogforge.agents.runtime.openai_provider import OpenAIProvider, _task_receipt_ids
from analogforge.agents.runtime.wire_context import WireCodec
from tests.integration.platform.test_live_rehearsal import task_and_context
from tests.unit.platform.test_role_claim_references import objection, proposal_for


@pytest.mark.parametrize("role", ["scientific_critic", "evidence_passport"])
@pytest.mark.parametrize("empty", [False, True])
def test_live_claim_reference_schema_matches_exact_catalog_and_preserves_empty_or_unscoped_reviews(role, empty):
    known = [f"q:{uuid4()}", f"v:{uuid4()}", f"discovery:{uuid4()}", "uncovered:req-1"]
    task, proposal = proposal_for(role, known[0])
    eligible = [] if empty else known
    task = task.model_copy(update={"payload": {**task.payload, "authoritative_claims": [
        {"claim_id": identifier} for identifier in eligible
    ]}})
    _, context, registry, counts, _ = task_and_context()
    context.role = role
    valid = deepcopy(proposal)
    if role == "scientific_critic":
        valid["payload"].update(accepted_claim_ids=eligible, objections=[objection(None)])
    else:
        template = valid["payload"]["claim_annotations"][0]
        valid["payload"]["claim_annotations"] = [{**template, "claim_id": identifier} for identifier in eligible]
    checked = []
    codec = WireCodec(task, _task_receipt_ids(task))

    class Client:
        def create(self, **kwargs):
            schema = next(tool["parameters"] for tool in kwargs["tools"] if tool["name"] == "submit_role_result")
            jsonschema.Draft202012Validator.check_schema(schema)
            validator = jsonschema.Draft202012Validator(schema)
            validator.validate(codec.encode(valid))
            if role == "scientific_critic" and eligible:
                validator.validate(codec.encode({**valid, "payload": {**valid["payload"], "objections": [
                    objection(identifier) for identifier in eligible
                ]}}))
            for identifier in [f"q:{uuid4()}", str(uuid4()), "unissued-claim", *(known if empty else [])]:
                if role == "scientific_critic":
                    for change in ({"accepted_claim_ids": [identifier]}, {"objections": [objection(identifier)]}):
                        with pytest.raises(jsonschema.ValidationError):
                            validator.validate(codec.encode({**valid, "payload": {**valid["payload"], **change}}))
                else:
                    invalid = {**valid, "payload": {**valid["payload"], "claim_annotations": [
                        {**proposal["payload"]["claim_annotations"][0], "claim_id": identifier}
                    ]}}
                    with pytest.raises(jsonschema.ValidationError):
                        validator.validate(codec.encode(invalid))
            checked.append(True)
            response = codec.encode(valid)
            if role == "scientific_critic":
                # A new finding ID is generated by the model, so it uses a literal UUID, not a client-owned alias.
                response["payload"]["objections"][0]["finding_id"] = valid["payload"]["objections"][0]["finding_id"]
            return {"status": "completed", "output": [{
                "type": "function_call", "name": "submit_role_result", "call_id": "review",
                "arguments": json.dumps(response),
            }]}

    result = OpenAIProvider(Client()).run(task, registry, context)
    assert checked == [True] and counts.count("model_requests_per_run") == 1
    assert result.payload == valid["payload"]
